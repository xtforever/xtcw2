-- Playlist-oriented music library.
--
-- Album identity is the M3U playlist, not the ID3 album tag.  Each library
-- entry stores an alias (display album name) and the playlist path.  Tracks
-- are read from the playlist in order; ID3 is used only for metadata and for
-- generating playlists for directories that do not contain one.

local id3 = require("id3")
local m3u = require("m3u")

local M = {}

local function shquote(s)
    return "'" .. tostring(s):gsub("'", "'\\''") .. "'"
end

local function exists(path)
    local f = io.open(path, "rb")
    if f then f:close(); return true end
    return false
end

local function basename(path)
    return (tostring(path or ""):match("([^/]+)$")) or tostring(path or "")
end

local function dirname(path)
    return (tostring(path or ""):match("^(.*)/[^/]*$")) or "."
end

local function canonical(path)
    if not path or path == "" then return path end
    local p = io.popen("realpath -m " .. shquote(path) .. " 2>/dev/null", "r")
    if not p then return path end
    local line = p:read("*l")
    p:close()
    return (line and line ~= "") and line or path
end

local function mkdir(path)
    os.execute("mkdir -p " .. shquote(path))
end

local function find_files(dir, args)
    local p = io.popen("find -P " .. shquote(dir) .. " " .. args .. " 2>/dev/null", "r")
    if not p then return {} end
    local out = {}
    for line in p:lines() do
        if line ~= "" then out[#out + 1] = line end
    end
    p:close()
    table.sort(out)
    return out
end

local function find_playlists(dir)
    return find_files(dir, "-type f \\( -iname '*.m3u' -o -iname '*.m3u8' \\) -print")
end

local function find_mp3s(dir, extensions)
    extensions = extensions or { "mp3" }
    local pats = {}
    for _, ext in ipairs(extensions) do
        pats[#pats + 1] = "-iname " .. shquote("*." .. ext)
    end
    return find_files(dir, "-type f \\( " .. table.concat(pats, " -o ") .. " \\) -print")
end

local function read_tags(path)
    local ok, tags = pcall(id3.read, path)
    if ok and tags then return tags end
    return {}
end

function M.default_library_path()
    local base = os.getenv("XDG_DATA_HOME") or
                 ((os.getenv("HOME") or ".") .. "/.local/share")
    return base .. "/xtcw-mp3player/library.lua"
end

function M.default_playlist_dir()
    local base = os.getenv("XDG_DATA_HOME") or
                 ((os.getenv("HOME") or ".") .. "/.local/share")
    return base .. "/xtcw-mp3player/playlists"
end

function M.library_path(cfg)
    return (cfg and cfg.library_file) or M.default_library_path()
end

function M.playlist_dir(cfg)
    return (cfg and cfg.library_playlist_dir) or M.default_playlist_dir()
end

function M.load(cfg)
    local path = M.library_path(cfg)
    if not exists(path) then
        return { version = 1, entries = {} }
    end
    local chunk, err = loadfile(path)
    if not chunk then
        return { version = 1, entries = {} }, err
    end
    local ok, data = pcall(chunk)
    if not ok or type(data) ~= "table" then
        return { version = 1, entries = {} }, tostring(data)
    end
    data.version = data.version or 1
    data.entries = data.entries or {}
    return data
end

local function quote(v)
    if type(v) == "string" then return string.format("%q", v) end
    if type(v) == "number" or type(v) == "boolean" then return tostring(v) end
    return "nil"
end

function M.save(cfg, data)
    local path = M.library_path(cfg)
    mkdir(dirname(path))
    local tmp = path .. ".tmp." .. tostring(os.time()) .. "." .. tostring(math.random(100000))
    local f, err = io.open(tmp, "w")
    if not f then return nil, err end
    f:write("-- generated by xtcw mp3player playlist library\n")
    f:write("return {\n  version = 1,\n  entries = {\n")
    for _, e in ipairs(data.entries or {}) do
        f:write("    {")
        f:write(" alias=", quote(e.alias or ""))
        f:write(", playlist=", quote(e.playlist or ""))
        f:write(", source_dir=", quote(e.source_dir or ""))
        f:write(", generated=", quote(e.generated and true or false))
        f:write(", group_key=", quote(e.group_key or ""))
        f:write(", track_count=", quote(tonumber(e.track_count) or 0))
        f:write(", missing=", quote(e.missing and true or false))
        f:write(", last_scan=", quote(tonumber(e.last_scan) or 0))
        f:write(" },\n")
    end
    f:write("  },\n}\n")
    f:close()
    local ok, rerr = os.rename(tmp, path)
    if not ok then
        os.remove(tmp)
        return nil, rerr
    end
    return true
end

local function entry_by_playlist(data, playlist)
    local want = canonical(playlist)
    for i, e in ipairs(data.entries) do
        if canonical(e.playlist) == want then return e, i end
    end
    return nil, nil
end

local function alias_used(data, alias, exclude)
    for _, e in ipairs(data.entries) do
        if e ~= exclude and tostring(e.alias):lower() == tostring(alias):lower() then
            return true
        end
    end
    return false
end

local function unique_alias(data, alias, exclude)
    alias = tostring(alias or "Album")
    if alias == "" then alias = "Album" end
    if not alias_used(data, alias, exclude) then return alias end
    local n = 2
    while alias_used(data, alias .. " (" .. n .. ")", exclude) do n = n + 1 end
    return alias .. " (" .. n .. ")"
end

local function sanitize(name)
    name = tostring(name or "Album")
    name = name:gsub("[/\\:*?\"<>|]", "_")
    name = name:gsub("^%s+", ""):gsub("%s+$", "")
    if name == "" then name = "Album" end
    return name
end

local function generated_playlist_path(cfg, data, alias)
    local dir = M.playlist_dir(cfg)
    mkdir(dir)
    local base = sanitize(alias)
    local path = dir .. "/" .. base .. ".m3u"
    local n = 2
    while exists(path) do
        local e = entry_by_playlist(data, path)
        if not e then break end
        path = dir .. "/" .. base .. " (" .. n .. ").m3u"
        n = n + 1
    end
    return path
end

local function find_generated(data, source_dir, group_key)
    for _, e in ipairs(data.entries) do
        if e.generated and canonical(e.source_dir) == canonical(source_dir) and
           tostring(e.group_key) == tostring(group_key) then
            return e
        end
    end
    return nil
end

local function playlist_default_alias(playlist, list)
    local album, mixed = nil, false
    for _, e in ipairs(list or {}) do
        if exists(e.path) then
            local tags = read_tags(e.path)
            local a = tostring(tags.album or "")
            if a ~= "" then
                if album == nil then
                    album = a
                elseif album ~= a then
                    mixed = true
                    break
                end
            end
        end
    end
    if album and not mixed then return album end
    return basename(playlist):gsub("%.[Mm][3][Uu]8?$", "")
end

local function add_or_update(data, entry)
    local old, idx = entry_by_playlist(data, entry.playlist)
    if old then
        entry.alias = old.alias or entry.alias
        data.entries[idx] = entry
        return false
    end
    data.entries[#data.entries + 1] = entry
    return true
end

local function track_sort_key(item)
    local tags = item.tags or {}
    local track = tonumber(tostring(tags.track or ""):match("^(%d+)")) or 0
    return string.format("%06d\0%s", track, tostring(tags.title or item.path))
end

function M.add_directory(cfg, dir)
    dir = canonical(dir)
    if not exists(dir) then return nil, "directory not found: " .. tostring(dir) end

    local data, lerr = M.load(cfg)
    if not data then return nil, lerr end

    local summary = { added = 0, updated = 0, generated = 0, warnings = {} }
    local referenced = {}

    for _, playlist in ipairs(find_playlists(dir)) do
        local list, perr = m3u.read(playlist)
        if list then
            for _, e in ipairs(list) do
                referenced[canonical(e.path)] = true
            end
            local alias = playlist_default_alias(playlist, list)
            local entry = {
                alias = alias,
                playlist = canonical(playlist),
                source_dir = dir,
                generated = false,
                group_key = "",
                track_count = #list,
                missing = false,
                last_scan = os.time(),
            }
            local old = entry_by_playlist(data, entry.playlist)
            if old then
                entry.alias = old.alias or entry.alias
                summary.updated = summary.updated + 1
            else
                entry.alias = unique_alias(data, entry.alias)
                summary.added = summary.added + 1
            end
            add_or_update(data, entry)
        else
            summary.warnings[#summary.warnings + 1] = playlist .. ": " .. tostring(perr)
        end
    end

    local groups, order = {}, {}
    for _, path in ipairs(find_mp3s(dir, cfg.extensions)) do
        if not referenced[canonical(path)] then
            local tags = read_tags(path)
            local album = tostring(tags.album or "")
            local artist = tostring(tags.albumartist or tags.artist or "")
            local key
            if album ~= "" then
                key = artist .. "\0" .. album
            else
                key = "dir\0" .. dirname(path)
            end
            if not groups[key] then
                groups[key] = {
                    key = key,
                    album = album,
                    dir = dirname(path),
                    items = {},
                }
                order[#order + 1] = key
            end
            groups[key].items[#groups[key].items + 1] = { path = path, tags = tags }
        end
    end

    for _, key in ipairs(order) do
        local g = groups[key]
        table.sort(g.items, function(a, b)
            return track_sort_key(a) < track_sort_key(b)
        end)
        local alias = (g.album ~= "" and g.album) or basename(g.dir)
        local old = find_generated(data, dir, key)
        local playlist = old and old.playlist or generated_playlist_path(cfg, data, alias)
        local out = {}
        for _, item in ipairs(g.items) do
            out[#out + 1] = {
                file = item.path,
                title = item.tags.title or basename(item.path),
                duration = item.tags.duration,
            }
        end
        local ok, werr = m3u.write(playlist, out)
        if ok then
            local entry = {
                alias = old and old.alias or unique_alias(data, alias),
                playlist = canonical(playlist),
                source_dir = dir,
                generated = true,
                group_key = key,
                track_count = #out,
                missing = false,
                last_scan = os.time(),
            }
            if add_or_update(data, entry) then summary.added = summary.added + 1
            else summary.updated = summary.updated + 1 end
            summary.generated = summary.generated + 1
        else
            summary.warnings[#summary.warnings + 1] = playlist .. ": " .. tostring(werr)
        end
    end

    local ok, serr = M.save(cfg, data)
    if not ok then return nil, serr end
    return summary
end

function M.entries(cfg)
    local data = M.load(cfg)
    return data.entries
end

-- If the library file is still empty, import cfg.music_dir once and persist
-- the generated playlists + library entries.  Subsequent starts are cheap.
function M.ensure(cfg)
    local entries = M.entries(cfg)
    if #entries > 0 then return entries, false end
    local dir = cfg and cfg.music_dir
    if not dir or dir == "" or not exists(dir) then return entries, false end
    local summary, err = M.add_directory(cfg, dir)
    if not summary then return entries, false, err end
    return M.entries(cfg), true, summary
end

function M.tracks(cfg, entry)
    local list, err = m3u.read(entry.playlist)
    if not list then return {}, { tostring(err) } end
    local tracks, warnings = {}, {}
    for i, e in ipairs(list) do
        if exists(e.path) then
            local tags = read_tags(e.path)
            local title = tags.title
            if not title or title == "" then title = e.title end
            if not title or title == "" then title = basename(e.path) end
            tracks[#tracks + 1] = {
                path = e.path,
                file = basename(e.path),
                title = title,
                artist = tags.artist or "Unknown Artist",
                album = entry.alias or tags.album or "",
                albumartist = tags.albumartist or tags.artist or "Unknown Artist",
                track = tags.track or "",
                disc = tags.disc or "",
                year = tags.year or "",
                genre = tags.genre or "",
                duration = e.duration or tags.duration,
                playlist = entry.playlist,
                playlist_index = i,
                tags = tags,
            }
        else
            warnings[#warnings + 1] = "missing: " .. tostring(e.path)
        end
    end
    return tracks, warnings
end

function M.queue(cfg, entries)
    entries = entries or M.entries(cfg)
    local queue = {}
    for ai, entry in ipairs(entries) do
        local tracks = M.tracks(cfg, entry)
        for _, t in ipairs(tracks) do
            t.album_index = ai
            t.album_alias = entry.alias
            queue[#queue + 1] = t
        end
    end
    return queue
end

function M.album_groups(queue)
    local groups, last = {}, nil
    for i, t in ipairs(queue or {}) do
        local key
        if t.album_index then
            key = "i:" .. tostring(t.album_index)
        else
            key = "a:" .. tostring(t.album or "") .. "\0" .. tostring(t.albumartist or "")
        end
        if key ~= last then
            groups[#groups + 1] = {
                key = key,
                first = i,
                last = i,
                album = t.album_alias or t.album or "",
            }
            last = key
        else
            groups[#groups].last = i
        end
    end
    return groups
end

function M.next_album(queue, index)
    local groups = M.album_groups(queue)
    for gi, g in ipairs(groups) do
        if g.last >= index then
            if g.first > index then return g.first end
            local n = groups[gi + 1] or groups[1]
            return n.first
        end
    end
    return 1
end

function M.prev_album(queue, index)
    local groups = M.album_groups(queue)
    if #groups == 0 then return 1 end
    for gi, g in ipairs(groups) do
        if g.first >= index then
            local p = groups[gi - 1] or groups[#groups]
            return p.first
        end
    end
    return groups[#groups].first
end

function M.rename(cfg, playlist, alias)
    local data = M.load(cfg)
    local e = entry_by_playlist(data, playlist)
    if not e then return nil, "playlist not found" end
    e.alias = unique_alias(data, alias, e)
    local ok, err = M.save(cfg, data)
    if not ok then return nil, err end
    return true, e.alias
end

function M.remove(cfg, playlist, delete_generated)
    local data = M.load(cfg)
    local e, idx = entry_by_playlist(data, playlist)
    if not e then return nil, "playlist not found" end
    if delete_generated and e.generated then
        local managed = canonical(M.playlist_dir(cfg)) .. "/"
        if canonical(e.playlist):sub(1, #managed) == managed then
            os.remove(e.playlist)
        end
    end
    table.remove(data.entries, idx)
    local ok, err = M.save(cfg, data)
    if not ok then return nil, err end
    return true
end

function M.rescan(cfg)
    local data = M.load(cfg)
    local dirs = {}
    for _, e in ipairs(data.entries) do
        if e.source_dir and e.source_dir ~= "" then dirs[e.source_dir] = true end
    end
    for dir in pairs(dirs) do
        M.add_directory(cfg, dir)
    end

    data = M.load(cfg)
    for _, e in ipairs(data.entries) do
        if exists(e.playlist) then
            local list = m3u.read(e.playlist)
            e.track_count = list and #list or 0
            e.missing = false
        else
            e.track_count = 0
            e.missing = true
        end
        e.last_scan = os.time()
    end
    local ok, err = M.save(cfg, data)
    if not ok then return nil, err end
    return true
end

return M
