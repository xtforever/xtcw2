#!/bin/bash

gen_header()
{
echo "/* generated by widreg.sh */"
echo "#ifndef ${OUT^^}_H"
echo "#define ${OUT^^}_H"
echo "#include <X11/IntrinsicP.h>"
echo "#include \"WcCreateP.h\""
for a in ${names[@]}
do
    echo "#include <xtcw/$a.h>"
    if ! [ -f "$INC/$a.h" ]
    then
	echo error "$INC/$a.h" 
    fi
done

echo "void widreg(XtAppContext app);"

echo "#endif"
}

gen_code()
{
echo "/* generated by widreg.sh */"
echo "#include \"${OUT}.h\""
echo "#include \"WcCreateP.h\""

echo "void widreg(XtAppContext app) {"
for a in ${names[@]}
do
    echo "WcRegisterClassPtr(app, \"$a\", ${a,}WidgetClass );"
done
echo "}"
}


src=(widgets/*.widget)
names=(${src[@]##widgets/})
names=(${names[@]%%.widget})

OUT=widreg
INC=generated
SRC=generated

gen_header >$SRC/$OUT.h
gen_code   >$SRC/$OUT.c
