-- cookbook/app/store/persistence.lua
-- Persistence helpers for the cookbook model.
--
-- NOTE: xtcw2 currently exposes no JSON / structured file read-write binding to
-- Lua (only the C `task_copy` file-copy binding). These helpers therefore use
-- plain Lua `io`, which is enough for a reference app but is one of the gaps
-- recorded in ../plan-xtcw-completed.md.

local M = {}

-- Serialise a Lua value (table/string/number/boolean/nil) to Lua source.
local function to_lua(v, indent)
    indent = indent or ""
    local t = type(v)
    if t == "string" then
        return string.format("%q", v)
    elseif t == "number" or t == "boolean" then
        return tostring(v)
    elseif t == "nil" then
        return "nil"
    elseif t == "table" then
        local parts = { "{" }
        local inner = indent .. "  "
        for k, val in pairs(v) do
            local key
            if type(k) == "number" then
                key = "[" .. tostring(k) .. "]"
            else
                key = string.format("[%q]", k)
            end
            parts[#parts + 1] = inner .. key .. " = " .. to_lua(val, inner) .. ","
        end
        parts[#parts + 1] = indent .. "}"
        return table.concat(parts, "\n")
    end
    return "nil"
end

M.to_lua = to_lua

-- Load recipes from a file. Returns a list of recipe tables, or nil + error.
-- The on-disk format is a Lua chunk returning a table (see save()).
function M.load(path)
    local f, err = io.open(path, "r")
    if not f then
        return nil, err
    end
    local source = f:read("*a")
    f:close()

    local chunk, lerr = load(source, "@" .. path, "t", {})
    if not chunk then
        return nil, lerr
    end
    local ok, data = pcall(chunk)
    if not ok then
        return nil, data
    end
    if type(data) ~= "table" then
        return nil, "expected a table"
    end
    return data
end

-- Save recipes to a file. Returns true or nil + error.
function M.save(path, recipes)
    local f, err = io.open(path, "w")
    if not f then
        return nil, err
    end
    f:write("-- generated by cookbook/app/store/persistence.lua\nreturn ")
    f:write(to_lua(recipes))
    f:write("\n")
    f:close()
    return true
end

return M
